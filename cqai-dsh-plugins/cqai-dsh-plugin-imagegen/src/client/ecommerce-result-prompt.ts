import type { EcommerceRunSlot } from '../ecommerce-run-protocol.ts'

export interface EcommerceResultPrompt {
  prompt: string | null
  source: 'actual' | 'saved' | 'planned' | 'unavailable'
  attempt?: number
}

const hasPrompt = (value: unknown): value is string => typeof value === 'string' && value.trim() !== ''

/** Resolve the prompt for this exact displayed image, independently of the
 * slot's current status. Its old result remains visible during a retry. */
export function ecommerceResultPrompt(
  slot: EcommerceRunSlot,
  imageIndex: number,
  options: { legacy?: boolean } = {},
): EcommerceResultPrompt {
  const unavailable: EcommerceResultPrompt = { prompt: null, source: 'unavailable' }
  if (!Number.isInteger(imageIndex) || imageIndex < 0) return unavailable
  const displayed = slot.images?.[imageIndex]
  if (!displayed || typeof displayed.url !== 'string' || displayed.url === '') return unavailable

  // Attempt arrays are appended in generation order. A shared content hash
  // can recur across attempts: use the latest completed, matching image.
  for (let index = (slot.attempts?.length ?? 0) - 1; index >= 0; index--) {
    const attempt = slot.attempts![index]
    if (attempt.status !== 'completed') continue
    const image = attempt.images?.[imageIndex]
    if (!image || image.url !== displayed.url) continue
    if (image.mime && displayed.mime && image.mime !== displayed.mime) continue
    if (hasPrompt(attempt.request?.prompt)) {
      return { prompt: attempt.request.prompt, source: 'actual', attempt: attempt.number }
    }
    // Matching metadata with no prompt cannot be replaced by a different,
    // older request merely because the generated bytes happen to be equal.
    break
  }

  // The original plan and legacy saved text are useful to inspect, but do not
  // prove which request produced the displayed result. Never use a running
  // attempt's request as a substitute for the old result's missing record.
  if (!hasPrompt(slot.request?.prompt)) return unavailable
  return { prompt: slot.request.prompt, source: options.legacy ? 'saved' : 'planned' }
}
